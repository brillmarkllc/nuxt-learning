#!/usr/bin/env python3
"""Regenerate assets/js/manifest.js from topics/*.md.

Run this after adding, removing, or renaming files in topics/. It never
modifies anything under topics/ — it only reads the first "# " heading and
"Course section: <num>: <name>" line out of each file to build the sidebar
navigation data consumed by assets/js/app.js.

Usage: python3 scripts/generate-manifest.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOPICS = ROOT / "topics"

files = sorted(p.name for p in TOPICS.glob("*.md"))

home = None
pages = []

for fname in files:
    text = (TOPICS / fname).read_text(encoding="utf-8")
    title_match = re.search(r"^#\s+(.+)$", text, re.MULTILINE)
    title = title_match.group(1).strip() if title_match else fname
    section_match = re.search(r"^Course section:\s*(.+)$", text, re.MULTILINE)
    file_id = fname[:-3]  # strip .md

    if section_match is None:
        if home is not None:
            print(f"warning: multiple files have no 'Course section:' line; "
                  f"using {home['file']} as home, ignoring {fname}")
            continue
        home = {"file": fname, "id": file_id, "title": title}
        continue

    rest = section_match.group(1).strip()
    if ":" in rest:
        num, name = rest.split(":", 1)
        num, name = num.strip(), name.strip()
    else:
        num, name = rest, rest

    pages.append({
        "file": fname,
        "id": file_id,
        "title": title,
        "sectionNum": num,
        "sectionTitle": name,
    })

if home is None:
    raise SystemExit("No home page found: exactly one topics/*.md file must have no "
                      "'Course section:' line (it becomes the course index).")

out = [
    "// Auto-generated by scripts/generate-manifest.py from /topics — do not edit",
    "// topics/ files to change this; rerun the script instead.",
    "window.SITE_HOME = " + json.dumps(home, indent=2) + ";",
    "window.SITE_TOPICS = " + json.dumps(pages, indent=2) + ";",
]

manifest_path = ROOT / "assets" / "js" / "manifest.js"
manifest_path.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {manifest_path} with {len(pages)} topics, home = {home['file']}")
